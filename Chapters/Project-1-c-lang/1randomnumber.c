#include <stdio.h>
#include <stdlib.h>
#include <time.h>

int main()
{
    int number;
    srand(time(0));
    number = rand() % 100 + 1;
    printf("number is %d", number);
    return 0;
}
/*  srand() is a function in C (defined in stdlib.h) used to set the seed for the random number generator function rand(). The rand() function generates a sequence of pseudo-random numbers, but it needs a starting point, called a seed, to initiate the sequence.

By default, if you don't use srand(), the seed is set to the same value every time you run the program, so the sequence of random numbers generated by rand() will be the same each time you execute the program. Using srand() with a different seed value allows you to generate a different sequence of random numbers.

To ensure a more "random" sequence (e.g., for a game or simulation), seed the random number generator with something that changes, like the current time using srand(time(0));

A common way to use srand() is to seed it with the current time, which changes every second. This ensures that every time the program runs, it generates a different sequence of random numbers.

rand() % 100: This gives a number between 0 and 99 (because the remainder when dividing by 100 will always be between 0 and 99).

Add 1: To get a number between 1 and 100, simply add 1 to the result of rand() % 100. This shifts the range from 0-99 to 1-100.

The largest number rand() % 100 can produce is 99 because if the random number is exactly one less than a multiple of 100 (e.g., 99, 199, 299, etc.), the remainder is 99
*/